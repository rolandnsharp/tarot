// GetMajorArt returns the 24x40 inner pixel art for a Major Arcana card.
func GetMajorArt(number int) string {
	if art, ok := majorArt[number]; ok {
		return art
	}
	return fallbackMajorArt(number)
}

func fallbackMajorArt(_ int) string {
	rows := make([]string, 40)
	for i := range rows {
		rows[i] = strings.Repeat("2", 24)
	}
	return strings.Join(rows, "\n")
}
