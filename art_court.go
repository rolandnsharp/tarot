// GetCourtArt returns the 24×40 inner pixel art for a court card,
// recolored for the given suit.
func GetCourtArt(number int, suit Suit) string {
	var tmpl string
	switch number {
	case 11:
		tmpl = pageTemplate
	case 12:
		tmpl = knightTemplate
	case 13:
		tmpl = queenTemplate
	case 14:
		tmpl = kingTemplate
	default:
		tmpl = pageTemplate
	}

	// Strip leading newline
	tmpl = strings.TrimPrefix(tmpl, "\n")

	primary := suit.PrimaryColor()
	secondary := suit.SecondaryColor()

	result := make([]byte, len(tmpl))
	for i := range tmpl {
		switch tmpl[i] {
		case 'P':
			result[i] = primary
		case 'S':
			result[i] = secondary
		default:
			result[i] = tmpl[i]
		}
	}
	return string(result)
}
